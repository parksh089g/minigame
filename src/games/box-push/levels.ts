/** 적어 둔 것 한 줄을 읽는다. 읽을 수 없으면 null이다. */
export function parseLevel(entry: string): Puzzle | null {
  const match = /^(\d+) (\S+)$/.exec(entry);
  return match ? parsePuzzle(match[2], Number(match[1])) : null;
}

/** 단계 모드의 level(1부터)번째 단계의 판. 같은 단계는 언제 누가 해도 같은 판이다. */
export function levelPuzzle(level: number): Puzzle {
  const entry = LEVEL_CODES[(toLevel(level) - 1) % Math.max(1, LEVEL_CODES.length)];
  return (entry === undefined ? null : parseLevel(entry)) ?? fallbackPuzzle(1);
}

/** 단계 모드의 한 단계. 시간은 흐르지 않고, 그 판을 깨면 끝난다. */
export function levelRun(level: number): RunState {
  return puzzleRun(levelPuzzle(level));
}

