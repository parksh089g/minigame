/** 둘레에 0번 색 테두리를 한 칸 붙인다. */
export function withOutline(rows: Rows): Rows {
  const height = rows.length;
  const width = rows[0]?.length ?? 0;
  const filled = (x: number, y: number): boolean => {
    const cell = rows[y]?.[x];
    return cell !== undefined && cell !== '.';
  };
  const out: string[] = [];
  for (let y = -1; y <= height; y += 1) {
    let line = '';
    for (let x = -1; x <= width; x += 1) {
      if (filled(x, y)) line += rows[y][x];
      else if (filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1)) line += '0';
      else line += '.';
    }
    out.push(line);
  }
  return out;
}

/** 정사각형 size칸 안에 놓는다. bottom이면 아래 가운데, 아니면 한가운데. */
export function placeIn(rows: Rows, size: number, bottom: boolean): Rows {
  const width = rows[0]?.length ?? 0;
  const left = Math.floor((size - width) / 2);
  const top = bottom ? size - rows.length : Math.floor((size - rows.length) / 2);
  const blank = '.'.repeat(size);
  return Array.from({ length: size }, (_, y) => {
    const row = rows[y - top];
    if (row === undefined) return blank;
    return '.'.repeat(left) + row + '.'.repeat(size - width - left);
  });
}
