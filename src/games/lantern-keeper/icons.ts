/** 텍스처 이름 */
export const iconKey = (id: IconId): string => `lk-icon-${id}`;

/** 이 선택지에 붙일 아이콘. 진화형이 되는 선택지는 진화한 모습을 보여 준다. */
export function upgradeIcon(upgrade: Upgrade): IconId {
  switch (upgrade.type) {
    case 'weapon':
      return isEvolved(upgrade.level) ? `${upgrade.id}Evo` : upgrade.id;
    case 'passive':
    case 'boon':
      return upgrade.id;
    case 'heal':
      return 'heal';
    case 'embers':
      return 'embers';
  }
}

/** HUD의 칸 하나: 무엇을 얼마나 올렸는지 */
export interface Slot {
  icon: IconId;
  level: number;
  /** 최종 진화형이 된 무기 */
  evolved: boolean;
}

/** levels에 처음 들어온 순서, 곧 얻은 순서대로 늘어놓는다. */
function owned<K extends string>(levels: Levels<K>): Array<[K, number]> {
  return (Object.keys(levels) as K[])
    .map((id): [K, number] => [id, levels[id] ?? 0])
    .filter(([, level]) => level > 0);
}

/** 지금 든 무기를 얻은 순서대로. 진화한 무기는 진화한 모습의 아이콘으로 보인다. */
export function weaponSlots(weapons: Levels<WeaponId>): Slot[] {
  return owned(weapons).map(([id, level]) => ({
    icon: upgradeIcon({ type: 'weapon', id, level }),
    level,
    evolved: isEvolved(level),
  }));
}

/** 지금 가진 패시브를 얻은 순서대로 */
export function passiveSlots(passives: Levels<PassiveId>): Slot[] {
  return owned(passives).map(([id, level]) => ({ icon: id, level, evolved: false }));
}

const OUTLINE = '0';

/**
 * 그림 둘레에 한 픽셀짜리 검은 테두리를 두른다. 테두리가 잘리지 않게 사방으로 한 픽셀씩 커진다.
 * 색이 있는 픽셀과 위아래나 옆으로 맞닿은 빈 칸이 테두리가 된다.
 */
export function withOutline(rows: Rows): Rows {
  const height = rows.length;
  const width = rows[0]?.length ?? 0;
  const filled = (x: number, y: number): boolean => {
    const cell = rows[y]?.[x];
    return cell !== undefined && cell !== '.';
  };
  const out: string[] = [];
  for (let y = -1; y <= height; y += 1) {
    let line = '';
    for (let x = -1; x <= width; x += 1) {
      if (filled(x, y)) line += rows[y][x];
      else if (filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1)) line += OUTLINE;
      else line += '.';
    }
    out.push(line);
  }
  return out;
}
