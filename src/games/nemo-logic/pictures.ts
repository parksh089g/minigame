/**
 * 네모 로직의 단계 모드에서 그리는 그림들. 단계마다 그림이 하나씩이고, 다 칠하면 색이 입혀져서 무엇인지 드러난다.
 * 그림은 글자로 그린다: 점(.)은 비워 두는 칸이고, 글자는 칠하는 칸이며 그 글자가 다 칠했을 때의 색이다(PICTURE_COLORS).
 * 푸는 동안에는 색이 보이지 않으므로 색은 문제에 영향을 주지 않는다.
 *
 * 그림을 고치거나 늘릴 때 지킬 것(pictures.test.ts가 확인한다):
 * - 찍지 않고 한 줄씩 따져서 풀 수 있어야 한다. 그래야 숫자에 맞는 그림이 하나뿐이다.
 * - 가로는 8칸, 세로는 10칸까지. 비어 있는 줄이 없고, 한 줄에 숫자가 네 개를 넘지 않는다.
 * - 작은 그림부터 큰 그림으로 놓는다. 이미 깬 단계의 그림이 바뀌지 않게, 새 그림은 되도록 자리를 지켜 넣는다.
 * - 이름은 글꼴에 들어 있는 완성형 한글만 쓴다.
 */

export interface Picture {
  /** 다 칠했을 때 알려 주는 이름 */
  name: string;
  /** 위에서부터 한 줄씩. 줄의 길이는 모두 같다. */
  rows: readonly string[];
}

/** 그림의 글자가 가리키는 색 */
export const PICTURE_COLORS: Readonly<Record<string, number>> = {
  /** 빨강 */
  r: 0xf2707a,
  /** 주황 */
  o: 0xffa45c,
  /** 노랑 */
  y: 0xffcf5c,
  /** 연두 */
  g: 0x7fd38a,
  /** 짙은 초록 */
  G: 0x3f9f72,
  /** 하늘 */
  b: 0x7dbef2,
  /** 파랑 */
  B: 0x4f8fd6,
  /** 보라 */
  v: 0x9684e0,
  /** 분홍 */
  p: 0xff9fb5,
  /** 갈색 */
  n: 0xb3703e,
  /** 살구 */
  c: 0xffd9a8,
  /** 검정 */
  k: 0x4a3545,
  /** 회색 */
  s: 0xa9a3ad,
  /** 하양 */
  w: 0xffffff,
};

/** 비워 두는 칸을 적는 글자 */
const BLANK = '.';

/** 칸마다 칠하는 칸인지. 왼쪽 위부터 가로줄을 따라 적는다. */
export function paintedOf(picture: Picture): boolean[] {
  return picture.rows.flatMap((row) => [...row].map((letter) => letter !== BLANK));
}

/** 칸마다 다 칠했을 때의 색. 비워 두는 칸은 null이다. */
export function colorsOf(picture: Picture): (number | null)[] {
  return picture.rows.flatMap((row) =>
    [...row].map((letter) => (letter === BLANK ? null : (PICTURE_COLORS[letter] ?? null))),
  );
}

function picture(name: string, art: string): Picture {
  return {
    name,
    rows: art
      .split('\n')
      .map((row) => row.trim())
      .filter((row) => row.length > 0),
  };
}

